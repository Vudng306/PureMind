const DICT: Record<Lang, Record<Key, string>> = { vi: VI, en: EN };

export type Vars = Record<string, string | number>;

/** Điền `{tên}` bằng giá trị tương ứng; thiếu giá trị thì giữ nguyên chỗ trống. */
function fill(text: string, vars?: Vars): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  return fill(DICT[lang][key] ?? DICT.vi[key] ?? key, vars);
}

/** Ngôn ngữ đang chọn, đọc được ở ngoài React (hàm xử lý lỗi, tiện ích). */
export { currentLang };

export type T = (key: Key, vars?: Vars) => string;

/** Hàm dịch gắn với ngôn ngữ đang chọn; component nào gọi nó sẽ tự vẽ lại khi đổi ngôn ngữ. */
export function useT(): T {
  const lang = usePreferences((s) => s.language);
  return (key, vars) => translate(lang, key, vars);
}

export function useLang(): Lang {
  return usePreferences((s) => s.language);
}

/** An SRS message shown on screen rather than caught in a handler: it follows the language too. */
export function useMsg(): (code: MsgCode) => string {
  const lang = usePreferences((s) => s.language);
  return (code) => messageIn(lang, code);
}
